/*
Вопрос 1: Что делает malloc?

Ответ: malloc выделяет блок памяти заданного размера в байтах.
Возвращает указатель на начало блока или NULL при ошибке.
Память не очищается, содержит случайные значения.

Вопрос 2: Чем отличается malloc от calloc?

Ответ: malloc принимает один аргумент (размер в байтах) и не инициализирует память.
calloc принимает два аргумента (количество и размер элемента)
и заполняет всю память нулями.

Вопрос 3: Что делает realloc?

Ответ: realloc изменяет размер ранее выделенного блока памяти.
Может переместить блок, сохранив данные.
При увеличении новые элементы не инициализируются.

Вопрос 4: Что произойдет при утечке памяти?

Ответ: Программа будет потреблять все больше памяти,
что может привести к замедлению, нехватке памяти и крашу.

Вопрос 5: Зачем нужен free?

Ответ: free освобождает динамическую память, возвращая её системе.
Без free возникает утечка памяти.

Вопрос 6: Что произойдет при двойном освобождении памяти?

Ответ: Неопределенное поведение: краш, повреждение данных или ошибка.

Вопрос 7: Как проверить, что malloc вернул NULL?

Ответ: if(ptr == NULL) { printf("Ошибка"); }

Вопрос 8: В чем отличие статического и динамического массива?

Ответ: Статический имеет фиксированный размер на этапе компиляции,
освобождается автоматически.
Динамический создается во время выполнения, размер можно менять,
требует ручного управления памятью.
*/