// Вопрос 1: Как объявить структуру в языке C?
// Ответ: Структура объявляется с помощью ключевого слова struct, 
// после которого указывается имя структуры, а в фигурных скобках 
// перечисляются поля с указанием их типов

// Вопрос 2: Что такое вложенные структуры и зачем они нужны?
// Ответ: Вложенные структуры - это структуры, которые содержат другие структуры 
// в качестве своих полей. Они нужны для логической группировки связанных данных, 
// создания иерархических моделей и повышения читаемости кода

// Вопрос 3: Как передать структуру в функцию?
// Ответ: Структуру можно передать двумя способами: по значению (создается копия, 
// изменения не влияют на оригинал) или по указателю (передается адрес, 
// изменения влияют на оригинал, экономия памяти)

// Вопрос 4: Можно ли создавать массивы структур?
// Ответ: Да, можно создавать массивы структур так же, как массивы любых других типов

// Вопрос 5: Как обратиться к элементу массива структур?
// Ответ: Сначала указывается индекс элемента в квадратных скобках, 
// затем через точку обращаемся к нужному полю

// Вопрос 6: Можно ли использовать enum внутри структуры?
// Ответ: Да, перечисление можно использовать как тип поля внутри структуры

// Вопрос 7: Можно ли сравнивать структуры оператором ==?
// Ответ: Нет, оператор == не работает со структурами. 
// Для сравнения нужно сравнивать каждое поле по отдельности