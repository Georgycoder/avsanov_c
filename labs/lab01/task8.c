#include <stdio.h>

int main() {
    int x = 2147483647;
    
    printf("x = %d\n", x);
    printf("x + 1 = %d\n", x + 1);
    printf("\nОбъяснение: Произошло переполнение. ");
    printf("Максимальное значение int - 2147483647. ");
    printf("При добавлении 1 число становится отрицательным ");
    printf("из-за особенностей представления чисел в двоичном коде.\n");
    
    return 0;
}